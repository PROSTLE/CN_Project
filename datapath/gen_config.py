"""Generate datapath/bpf/config_gen.h and build/agent.conf from config/glasswall.yaml."""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config/glasswall.yaml").read_text())
    feats = yaml.safe_load((ROOT / "config/features.yaml").read_text())
    dp = cfg["datapath"]
    for name in ("port_bitmap_words", "host_bitmap_words"):
        n = dp[name]
        if n & (n - 1):
            sys.exit(f"{name} must be a power of two")
    if len(feats["kernel_features"]) & (len(feats["kernel_features"]) - 1):
        sys.exit("kernel feature count must be a power of two (BPF index mask)")

    hdr = [
        "/* GENERATED by datapath/gen_config.py from config/glasswall.yaml - do not edit */",
        "#ifndef GW_CONFIG_GEN_H",
        "#define GW_CONFIG_GEN_H",
        f"#define GW_MAX_RULES {dp['max_rules']}",
        f"#define GW_MAX_PRED {dp['max_pred']}",
        f"#define GW_PORT_BM_WORDS {dp['port_bitmap_words']}",
        f"#define GW_HOST_BM_WORDS {dp['host_bitmap_words']}",
        f"#define GW_FLOW_MAP_ENTRIES {dp['flow_map_entries']}",
        f"#define GW_SRC_MAP_ENTRIES {dp['src_map_entries']}",
        f"#define GW_VERDICT_MAP_ENTRIES {dp['verdict_map_entries']}",
        f"#define GW_RINGBUF_BYTES {dp['ringbuf_bytes']}",
        "#endif",
        "",
    ]
    (ROOT / "datapath/bpf/config_gen.h").write_text("\n".join(hdr))

    lab = cfg["lab"]
    safety = cfg["safety_allowlist"]
    conf = {
        "ifaces": ",".join(link["gw_if"] for link in lab["links"]),
        "server_iface": lab["server_iface"],
        "seq_len": dp["seq_len_n"],
        "window_ns": dp["src_window_ns"],
        "pps_min_elapsed_ns": dp["pps_min_elapsed_ns"],
        "reaper_ms": dp["reaper_interval_ms"],
        "events_sock": dp["events_socket"],
        "ctl_sock": dp["ctl_socket"],
        "safety_ports": ",".join(str(p) for p in safety["ports"]),
        "safety_ips": ",".join(safety["ips"]),
        "realizable": ",".join(f"{f['id']}:{f['name']}" for f in feats["kernel_features"]),
    }
    out = ROOT / "datapath/build"
    out.mkdir(exist_ok=True)
    (out / "agent.conf").write_text("".join(f"{k}={v}\n" for k, v in conf.items()))
    print("generated config_gen.h and build/agent.conf")


if __name__ == "__main__":
    main()
